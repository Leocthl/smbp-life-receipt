// Balance pass: N seeded lives per bot strategy -> BALANCE_REPORT.md
// Usage: npx tsx scripts/balance.ts [N=10000] [out]
// A full run (N >= 10000) writes BALANCE_REPORT.md; smaller runs print only, unless an output path is given.
import { writeFileSync } from 'node:fs';
import { LABELS } from '../src/data/endings';
import { BOT_IDS, type BotId } from '../src/engine/bots';
import { lifeStats, metrics, pickLabel } from '../src/engine/endings';
import { netWorth } from '../src/engine/finance';
import { playLife } from '../src/engine/sim';

const N = Number(process.argv[2] ?? 10_000);
/** the bot whose label "belongs" to it, for the own-label check */
const OWN: Record<BotId, string[]> = {
  saver: ['saverKing'], indexer: ['zenInvestor'], spender: ['moonlight'], panic: ['exitOnRed'],
  tipChaser: ['riskWinner', 'rollercoaster'], family: ['familyPillar'], debtor: ['debtJuggler'], balanced: ['steady'],
};

interface Row { bot: BotId; nw: number[]; happy: number; rel: number; bankrupt: number; labels: Record<string, number> }

const q = (xs: number[], p: number) => xs[Math.min(xs.length - 1, Math.floor(p * xs.length))];
const fmt = (v: number) => (Math.abs(v) >= 1e6 ? `${(v / 1e6).toFixed(2)}M` : `${Math.round(v / 1e3)}k`);
const pct = (v: number) => `${(v * 100).toFixed(1)}%`;

const rows: Row[] = [];
for (const bot of BOT_IDS) {
  const nw: number[] = [];
  let happy = 0, rel = 0, bankrupt = 0;
  const labels: Record<string, number> = {};
  for (let seed = 1; seed <= N; seed++) {
    const s = playLife(seed, bot);
    const plain = netWorth(playLife(seed, 'balanced', undefined, s.character));
    const st = lifeStats(s, plain);
    nw.push(st.netWorth);
    happy += st.avgHappiness / N;
    rel += st.avgRelationships / N;
    if (s.bankrupt) bankrupt += 1 / N;
    const id = pickLabel(metrics(s, st)).id;
    labels[id] = (labels[id] ?? 0) + 1;
  }
  nw.sort((a, b) => a - b);
  rows.push({ bot, nw, happy, rel, bankrupt, labels });
  process.stderr.write(`${bot} done\n`);
}

// Dominance: a strategy dominates if it is at least as good as every other strategy on all four outcomes.
const outcomes = (r: Row) => [q(r.nw, 0.5), r.happy, r.rel, 1 - r.bankrupt];
const dominators = rows.filter((a) => rows.every((b) => a === b || outcomes(a).every((v, i) => v >= outcomes(b)[i])));
const best = (f: (r: Row) => number) => rows.reduce((a, b) => (f(b) > f(a) ? b : a)).bot;
const ownShare = (r: Row) => OWN[r.bot].reduce((a, l) => a + (r.labels[l] ?? 0), 0) / N;
const modal = (r: Row) => Object.entries(r.labels).sort((a, b) => b[1] - a[1])[0][0];
const reached = new Set(rows.flatMap((r) => Object.keys(r.labels)));
const unreached = LABELS.map((l) => l.id).filter((l) => !reached.has(l));

const lines = [
  '# Balance report',
  '',
  `Generated by \`npx tsx scripts/balance.ts ${N}\`: ${N.toLocaleString('en')} seeded lives per bot strategy (seeds 1..${N}), full event deck.`,
  '',
  '## Dominance check',
  '',
  'Criterion: a strategy **dominates** if it is at least as good as every other strategy on all four outcomes at once:',
  'median net worth at 65, average happiness, average relationships, and staying out of bankruptcy.',
  '',
  `**Result: ${dominators.length === 0 ? 'PASS, no dominant strategy' : 'FAIL, dominated by ' + dominators.map((d) => d.bot).join(', ')}.**`,
  '',
  `- Richest (median): ${best((r) => q(r.nw, 0.5))}`,
  `- Happiest: ${best((r) => r.happy)}`,
  `- Closest relationships: ${best((r) => r.rel)}`,
  `- Safest (fewest bankruptcies): ${best((r) => -r.bankrupt)}`,
  '',
  '## Outcomes per strategy',
  '',
  '| Strategy | p10 net worth | Median | p90 | Bankrupt at least once | Avg happiness | Avg relationships |',
  '|---|---|---|---|---|---|---|',
  ...rows.map((r) => `| ${r.bot} | ${fmt(q(r.nw, 0.1))} | ${fmt(q(r.nw, 0.5))} | ${fmt(q(r.nw, 0.9))} | ${pct(r.bankrupt)} | ${r.happy.toFixed(1)} | ${r.rel.toFixed(1)} |`),
  '',
  'Net worth is nominal HK$ at 65, after the MPF lump sum, including property net of mortgage.',
  '',
  '## Ending labels per strategy',
  '',
  '| Strategy | Own label(s) | Share in own label | Most common label | Full spread |',
  '|---|---|---|---|---|',
  ...rows.map((r) => `| ${r.bot} | ${OWN[r.bot].join(' / ')} | ${pct(ownShare(r))} | ${modal(r)} | ${Object.entries(r.labels).sort((a, b) => b[1] - a[1]).map(([k, v]) => `${k} ${pct(v / N)}`).join(', ')} |`),
  '',
  `Every label reachable: **${unreached.length === 0 ? 'yes' : 'no, missing ' + unreached.join(', ')}**.`,
  `Strategies whose most common label is their own: ${rows.filter((r) => OWN[r.bot].includes(modal(r))).length} of ${rows.length}.`,
  `Strategies with under half their lives in their own label: ${rows.filter((r) => ownShare(r) < 0.5).map((r) => `${r.bot} (${pct(ownShare(r))})`).join(', ') || 'none'}.`,
  '',
  '## Margins (how close the check is)',
  '',
  'For each strategy, the outcomes on which no other strategy beats it, so you can see how much each PASS rests on one axis.',
  '',
  ...rows.map((r) => {
    const names = ['median net worth', 'happiness', 'relationships', 'staying out of bankruptcy'];
    const wins = names.filter((_, i) => rows.every((b) => outcomes(r)[i] >= outcomes(b)[i]));
    return `- ${r.bot}: ${wins.length ? 'best on ' + wins.join(', ') : 'not best on any single outcome'}`;
  }),
  '',
  '## Reading this honestly',
  '',
  '- The check is a Pareto test over eight hand-written bot styles, not over every possible play. A mixed human strategy',
  '  can do better than any bot; that is intended.',
  '- Spending styles (spender, debtor) are the happiest and closest to friends on average, but are the poorest at 65 and',
  '  most often go bankrupt. The game shows that trade-off rather than hiding it: happiness comes from the experiences',
  '  themselves, and the bankruptcy years cost happiness and credit.',
  '- Saver is the safest, indexer the richest; indexer only loses to saver on bankruptcy risk, so for a careful player the',
  '  real choice between them is risk tolerance.',
  '- Bankruptcy rates for the extreme styles are higher than real-world rates, because bots never change course.',
  '',
];
const out = process.argv[3] ?? (N >= 10_000 ? 'BALANCE_REPORT.md' : null);
if (out) writeFileSync(out, lines.join('\n'));
console.log(lines.slice(0, 30).join('\n'));
